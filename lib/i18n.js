  const LANGS = Object.freeze(["en", "id"]);
  const LOCALES = { en: "en-US", id: "id-ID" };
  let current = "en";

  function setLang(lang) {
    current = LANGS.includes(lang) ? lang : "en";
  }

  function getLang() {
    return current;
  }

  function t(key, params) {
    const table = STRINGS[current] || STRINGS.en;
    let s = table[key] ?? STRINGS.en[key] ?? key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    return s;
  }

  /** 1234 -> "1.2K" (en) / "1,2 rb" (id). */
  function count(n, lang = current) {
    n = Number(n) || 0;
    const loc = LOCALES[lang] || "en-US";
    const fmt = (v) => (Math.floor(v * 10) / 10).toLocaleString(loc, { maximumFractionDigits: 1 });
    if (n >= 1e6) return fmt(n / 1e6) + (lang === "id" ? " jt" : "M");
    if (n >= 1e3) return fmt(n / 1e3) + (lang === "id" ? " rb" : "K");
    return String(n);
  }

  function duration(sec) {
    sec = Math.max(0, Math.round(sec));
    const h = Math.floor(sec / 3600);
    const m = Math.floor((sec % 3600) / 60);
    const s = sec % 60;
    if (h) return t("dur.h", { h, m });
    if (m && s) return t("dur.ms", { m, s });
    if (m) return t("dur.m", { m });
    return t("dur.s", { s });
  }

  function locale() {
    return LOCALES[current];
  }

  const SapuI18n = { LANGS, STRINGS, setLang, getLang, t, count, duration, locale };
  root.SapuI18n = SapuI18n;
